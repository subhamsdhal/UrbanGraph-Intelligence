"""Structural optimization interface shared by temporal and graph trainers."""

from typing import Protocol


class TrainingPolicy(Protocol):
    @property
    def family(self) -> str: ...

    @property
    def calendar(self) -> bool: ...

    @property
    def epochs(self) -> int: ...

    @property
    def patience(self) -> int: ...

    @property
    def learning_rate(self) -> float: ...

    @property
    def weight_decay(self) -> float: ...

    @property
    def loss(self) -> str: ...

    @property
    def clip_norm(self) -> float: ...

    @property
    def accumulation(self) -> int: ...

    @property
    def batch_size(self) -> int: ...

    @property
    def max_train_windows(self) -> int: ...

    @property
    def max_validation_windows(self) -> int: ...

    @property
    def threads(self) -> int: ...

    @property
    def workers(self) -> int: ...

    @property
    def seed(self) -> int: ...

    @property
    def device(self) -> str: ...

    @property
    def precision(self) -> str: ...

    @property
    def deterministic(self) -> bool: ...

    @property
    def trial_seconds(self) -> int: ...

    @property
    def run_seconds(self) -> int: ...

    @property
    def memory_mb(self) -> int: ...

    @property
    def scaling(self) -> str: ...

    @property
    def scheduler(self) -> bool: ...

    def to_dict(self) -> dict[str, object]: ...
